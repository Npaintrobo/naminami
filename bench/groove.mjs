// 同心円溝で、回る操舵ユニットと回らないゴムを繋ぐ。
//
//   ・正方形の SAW 操舵ユニット（大）が上。ピンの配列を持つ
//   ・円形のゴムシート（小）が下で接地。上面に操舵軸中心の同心円溝
//   ・ピンが溝に嵌まる。操舵はユニットを回すだけで、ピンは溝に沿って接線に滑る
//   ・ゴムは回らない
//
// 確かめること:
//   1. 正方形は回しても円を覆い続けるか（「十分に大きい」の条件）
//   2. 波の運転中、ピンは半径方向に動く必要がないか
//   3. 溝の形状拘束（両方向駆動）は、片方向の接触と比べて何を買うのか
//   4. 操舵のときピンが溝を滑る距離と、そのトルク
//   5. 同心円の波形はシートの曲げ剛性を異方にする。どれくらいか
//
//   node bench/groove.mjs

const N = 12, P = 50;
const RPM = 300, OMEGA = RPM * Math.PI / 30;
const MU_G = 0.2;                 // 溝の中の摩擦係数（乾いた樹脂／ゴム、仮定値）
const LOAD = 20 * 9810 / 1000;    // 機体重量 [N]

console.log('■ 1. 正方形は回しても円を覆うか\n');
{
  /* 一辺 L の正方形を中心まわりに任意角回したとき、常に内側にある領域は
     半径 L/2 の円（＝内接円）。数値で確かめる。 */
  const L = 600, R = L / 2;
  let worst = 0, area = 0, tot = 0;
  const M = 400;
  for (let i = 0; i < M; i += 1) for (let j = 0; j < M; j += 1) {
    const x = (i / (M - 1) - 0.5) * L * 1.5, z = (j / (M - 1) - 0.5) * L * 1.5;
    const r = Math.hypot(x, z);
    if (r > R) continue;
    tot += 1;
    let inAll = true;
    for (let a = 0; a < 90; a += 1) {
      const c = Math.cos(a * Math.PI / 180), s = Math.sin(a * Math.PI / 180);
      const u = Math.abs(x * c + z * s), v = Math.abs(-x * s + z * c);
      if (u > L / 2 || v > L / 2) { inAll = false; worst = Math.max(worst, r); break; }
    }
    if (inAll) area += 1;
  }
  console.log(`  一辺 ${L}mm の正方形、直径 ${L}mm の円: 全回転角で覆えた画素 ${(area / tot * 100).toFixed(1)}%`);
  console.log(`  覆えなかった最小半径: ${worst === 0 ? '（なし）' : worst.toFixed(1) + 'mm'}`);
  console.log(`
  → **一辺 L の正方形は、回しても直径 L の内接円を必ず覆う。**
    これが「ユニットはゴムに対して十分に大きい」の正確な条件。ゴムの直径 ≤ 正方形の一辺。
    代償は面積比 π/4 = 78.5%。ユニットの 21.5% は操舵不変性のために遊ばせることになる。`);
}

console.log('\n■ 2. 運転中、ピンは半径方向に動く必要があるか\n');
{
  /* ピンの水平位置はユニットに固定。溝はそのピンの半径の同心円。
     波はピンを鉛直にしか動かさないので、半径方向の変位はゼロ。 */
  console.log('  波は  w = W·cos(k·s − Ω·t)  で、ピンに与えるのは鉛直変位だけ。');
  console.log('  ピンの水平位置はユニットに固定されているので、半径方向の変位は恒等的に 0。');
  console.log('  → **運転中はピンが溝を出ない。** 溝は鉛直の両方向拘束としてだけ働く。');
}

console.log('\n■ 3. 溝の両方向拘束は何を買うか\n');
{
  /* 前回の膜シミュは「膜表面が w = W·cos(φ) に厳密に従う」と置いていた。
     これは駆動側が押しも引きもできることを前提にしている。
     平らな界面（押すだけ）だと、膜は上へ押されるだけで下へは引けない。
     その場合の実効振幅は半分（0〜W）になり、a_eff = h·W·k も半分になる。 */
  const h = 5, lam = 100, k = 2 * Math.PI / lam;
  const rows = [
    ['溝で両方向拘束（−W 〜 +W）', 6],
    ['平らな界面・押すだけ（0 〜 +W、実効 W/2）', 3],
  ];
  console.log('  h=5mm λ=100mm 300rpm');
  console.log('    界面                                     実効振幅  a_eff    予測速度');
  for (const [lab, w] of rows) {
    const a = h * w * k;
    console.log(`    ${lab.padEnd(38)} ${w.toFixed(1).padStart(4)} mm  ${a.toFixed(2)} mm  ${(a * OMEGA).toFixed(0).padStart(4)} mm/s`);
  }
  console.log(`
  → **2倍。** 前回の膜シミュ（docs/membrane-wave.md）は膜が波に厳密に従うと置いていたが、
    これは押しも引きもできる界面を暗に仮定していた。同心円溝はその仮定を成り立たせる。
    平らな界面だと実効振幅が半分になり、速度も半分になる。
    **溝は「あると良い」ではなく、前回の数字の前提そのもの。**`);
}

console.log('\n■ 4. 操舵のときピンが溝を滑る距離とトルク\n');
{
  console.log('  ピン半径 r を Δψ 操舵すると、ピンは溝に沿って r·Δψ 滑る。');
  console.log('    ゴム直径   平均ピン半径   90°操舵での滑り距離   操舵トルク(μ=0.2)   720°/s での消費');
  for (const D of [200, 400, 600]) {
    const rMean = D / 2 * 2 / 3;                  // 円板上に一様分布したときの平均半径
    const slide = rMean * Math.PI / 2;
    const torque = MU_G * LOAD * rMean / 1000;    // [N·m]
    const power = torque * (720 * Math.PI / 180); // [W]
    console.log(`    ${String(D).padStart(4)} mm    ${rMean.toFixed(0).padStart(5)} mm      ` +
      `${slide.toFixed(0).padStart(5)} mm          ${torque.toFixed(1).padStart(5)} N·m      ${power.toFixed(0).padStart(4)} W`);
  }
  console.log(`
  → 操舵は「溝の中で全ピンを引きずる」動作になる。直径600mmだと 90° 操舵で
    ピンが 314mm 滑り、トルク 7.8 N·m が要る。**保持には要らない（動かすときだけ）**が、
    偏極操舵で「720°/s 操舵でも滑りが増えない」と言えたぶんが、この構成では
    **溝の摩擦損失 99 W** という別の形で出てくる。連続ではなく操舵中だけなので
    許容範囲だが、ゴム径に比例するので大径化すると効いてくる。
    気になるなら溝を転がり（ローラ）にすること。`);
}

console.log('\n■ 4b. 回転漏れ — 波を止めてユニットだけ回したらゴムは回るか\n');
{
  /* これが最重要の反証試験（円対称写像の中心原理）。
     ユニットを回すと、各ピンは溝の中を接線方向に滑るので、ゴムには
     同じ回転向きの摩擦トルクがかかる。ゴムが回らないのは、接地面の摩擦が
     それに勝つ場合だけ。

     ピンが円板上に一様分布するとき  Σ N_i·r_i = W·(2R/3)  なので

       溝から受ける駆動トルク   = μ_groove  · W · (2R/3)
       接地面が返す抵抗トルク   = μ_ground · W · (2R/3)

     半径の項が両方に共通で消えるので、条件は摩擦係数の大小だけになる。 */
  console.log('  ピンが一様分布なら Σ N·r = W·(2R/3) で、駆動側も抵抗側も同じ形。');
  console.log('  半径が消えるので、**回らない条件は μ_溝 < μ_接地 だけ**。\n');
  console.log('    μ_溝   μ_接地   トルク比（溝/接地）   判定');
  for (const [mg, mgr] of [[0.2, 0.6], [0.3, 0.6], [0.5, 0.6], [0.6, 0.6], [0.8, 0.6]]) {
    const ratio = mg / mgr;
    const verdict = ratio < 0.5 ? '回らない（余裕あり）'
                  : ratio < 1 ? '回らないが余裕が小さい' : '**回る（成立しない）**';
    console.log(`    ${mg.toFixed(1)}    ${mgr.toFixed(1)}         ${ratio.toFixed(2)}          ${verdict}`);
  }
  console.log(`
  → **設計条件は μ_溝 < μ_接地 のひとつだけ。** 半径にも荷重にもピン数にも依らない。
    接地ゴムは μ=0.6 前後が欲しく、溝は潤滑して μ=0.2 に落とせるので、余裕は3倍。
    ただし「回らない」は静止摩擦の話で、実際は毎回わずかに滑って累積する可能性がある。
    回転漏れ L_ψ = θ_rubber/ψ_unit は実測でしか出ない。ここは実機試験が要る。

    転がり（ローラ）にすれば μ_溝 は 0.01 台まで落ちるので、余裕は 60倍になる。
    §4 の操舵トルクも同時に下がる。**溝を転がりにするのは二重に効く。**`);
}

console.log('\n■ 5. 同心円の溝はシートの曲げ剛性を異方にする\n');
{
  /* 同心円に溝を彫ると、半径方向には蛇腹のように曲がりやすく、
     円周方向には溝が connected なので硬い。波は直線方向に進むので、
     位置によって曲げ剛性が変わる。 */
  const H = 6;                       // シート厚 [mm]
  console.log('  シート厚 6mm。溝の深さを変えて、半径方向と円周方向の曲げ剛性比を見る。');
  console.log('    溝深さ  残り肉厚  半径方向 EI 比  円周方向 EI 比   異方比');
  for (const d of [0, 1, 2, 3]) {
    const web = H - d;
    const radial = (web / H) ** 3;                       // 溝を横切る向き＝薄い所で曲がる
    const circ = 1 + 3 * (d / H) ** 2 * (d > 0 ? 1 : 0); // 溝が波形として効いて硬くなる（概算）
    console.log(`    ${String(d).padStart(3)} mm  ${String(web).padStart(5)} mm  ` +
      `${radial.toFixed(3).padStart(11)}  ${circ.toFixed(2).padStart(12)}   ${(circ / radial).toFixed(1).padStart(6)}倍`);
  }
  console.log(`
  → 溝深さ 2mm（厚6mmの1/3）で異方比は約 5倍。波は直線方向に進むので、
    半径方向成分と円周方向成分で曲げやすさが変わり、**波形が歪む**。
    上の「円周方向 EI」は波形板の概算式で、実測でも計算でもない。要検証。
    溝を浅くすれば異方は減るが、両方向拘束の効きも減る。ここはトレードオフ。`);
}

